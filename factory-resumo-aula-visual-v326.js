  function replaceSection(prompt, heading, replacement) {
    const start = prompt.indexOf(heading);
    if (start < 0) return prompt;
    const next = prompt.indexOf("\n\n## ", start + heading.length);
    const end = next < 0 ? prompt.length : next;
    return `${prompt.slice(0, start)}${replacement}${prompt.slice(end)}`;
  }

  function insertBefore(prompt, anchor, section) {
    const index = prompt.indexOf(anchor);
    if (index < 0) return prompt;
    const prefix = prompt.slice(0, index).trimEnd();
    const suffix = prompt.slice(index).trimStart();
    return `${prefix}\n\n${section}\n\n${suffix}`;
  }

  function patchPrompt(prompt) {
    const original = typeof prompt === "string" ? prompt : "";
    if (!original.includes(SIGNATURE)) return original;

    let updated = original;

    if (updated.includes(CAPITAL_HEADING)) {
      updated = replaceSection(updated, CAPITAL_HEADING, CAPITAL_SECTION);
    } else {
      updated = insertBefore(updated, "## CONTROLE OBJETIVO DE TÍTULOS, SUBTÓPICOS E LINHAS", CAPITAL_SECTION);
    }

    updated = replaceSection(updated, FORMAT_HEADING, FORMAT_SECTION);
    updated = replaceSection(updated, HIERARCHY_HEADING, HIERARCHY_SECTION);
    updated = replaceSection(updated, TITLES_HEADING, TITLES_SECTION);

    if (updated.includes(VISUAL_HEADING)) {
      updated = replaceSection(updated, VISUAL_HEADING, VISUAL_SECTION);
    } else {
      updated = insertBefore(updated, WORD_HEADING, VISUAL_SECTION);
    }

    return updated;
  }

  function currentState() {
    try {
      return typeof state !== "undefined" && state && typeof state === "object" ? state : null;
    } catch (_error) {
      return null;
    }
  }

  function currentDefaults() {
    try {
      return typeof defaultFactoryPromptLibrary !== "undefined" && defaultFactoryPromptLibrary && typeof defaultFactoryPromptLibrary === "object"
        ? defaultFactoryPromptLibrary
        : null;
    } catch (_error) {
      return null;
    }
  }

  function patchLibrary(library) {
    if (!library || typeof library !== "object" || typeof library.resumoAula !== "string") return false;
    const updated = patchPrompt(library.resumoAula);
    if (updated === library.resumoAula) return false;
    library.resumoAula = updated;
    return true;
  }

  function applyFactoryResumoAulaVisualPolicy() {
    const targetState = currentState();
    let changed = false;

    const defaults = currentDefaults();
    if (defaults) changed = patchLibrary(defaults) || changed;

    if (targetState?.factoryPromptLibrary) {
      const stateChanged = patchLibrary(targetState.factoryPromptLibrary);
      changed = stateChanged || changed;
      if (stateChanged) {
        targetState.migrations ||= {};
        targetState.migrations[MIGRATION_ID] ||= new Date().toISOString();
        try {
          if (typeof saveData === "function") saveData();
        } catch (error) {
          console.warn(`[${VERSION}] Não foi possível persistir imediatamente a atualização visual do RESUMO/AULA.`, error);
        }
      }
    }

    globalThis.__aldusFactoryResumoAulaVisualV326 = Object.freeze({
      version: VERSION,
      migrationId: MIGRATION_ID,
      applied: Boolean(targetState?.factoryPromptLibrary),
      changed,
      patchPrompt,
      updatedAt: new Date().toISOString()
    });

    return changed;
  }

  const run = () => {
    try {
      applyFactoryResumoAulaVisualPolicy();
    } catch (error) {
      console.error(`[${VERSION}] Falha ao aplicar a identidade visual do RESUMO/AULA.`, error);
    }
  };

